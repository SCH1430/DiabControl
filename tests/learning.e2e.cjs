async function storedData(page) {
  return page.evaluate(async () => {
    const local = Object.fromEntries(Object.keys(localStorage).sort().map(key => [key, localStorage.getItem(key)]));
    const session = Object.fromEntries(Object.keys(sessionStorage).sort().map(key => [key, sessionStorage.getItem(key)]));
    const databases = [];
    for (const definition of await indexedDB.databases()) {
      const db = await new Promise((resolve,reject) => { const request=indexedDB.open(definition.name); request.onsuccess=()=>resolve(request.result); request.onerror=()=>reject(request.error); });
      const stores = [];
      for (const name of Array.from(db.objectStoreNames)) {
        const records = await new Promise((resolve,reject) => { const request=db.transaction(name).objectStore(name).getAll(); request.onsuccess=()=>resolve(request.result); request.onerror=()=>reject(request.error); });
        stores.push({name,records});
      }
      databases.push({name:db.name,stores}); db.close();
    }
    return {local,session,databases};
  });
}
