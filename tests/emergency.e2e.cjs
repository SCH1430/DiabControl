/* Offline first-aid flows: thresholds, state priority, timers, plan gating, and mobile layouts. */
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { browserType, launchOptions, output } = require('./support.cjs');
const root = path.resolve(__dirname, '..');
let browser, checks = 0;
const check = (condition, name) => { assert.ok(condition, name); checks++; console.log('PASS ' + name); };
(async () => {
  await fs.mkdir(output, { recursive: true });
  browser = await browserType.launch(launchOptions);
  const context = await browser.newContext({ viewport: { width: 1380, height: 1050 }, timezoneId: 'Europe/Moscow' });
  await context.setOffline(true);
  const page = await context.newPage(), errors = [], requests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (/^https?:/.test(r.url())) requests.push(r.url()); });
  page.setDefaultTimeout(10000);
  await page.clock.install();
  const click = async selector => { await page.locator(selector).click(); await page.waitForFunction(() => !document.body.hasAttribute('aria-busy')); };
  const fill = (id,value) => page.locator('#'+id).fill(String(value));
  const text = selector => page.locator(selector).innerText();
  const close = () => page.keyboard.press('Escape');
  const chooseState = async selector => { if (await page.locator(selector).isHidden()) await click('#aidChangeState'); await click(selector); };
  const reading = async(value, unit = 'mmol') => { if (await page.locator('#aidMeasurement').isHidden()) await click('#aidNewReading'); await page.locator('#emergencyUnit').selectOption(unit); await fill('emergencySugarValue', value); await click('#emergencyEvaluateBtn'); };
  await page.goto(pathToFileURL(path.join(root,'index.html')).href);
  await click('#authQuickEmergency');
  check(await page.locator('#aidMeasurement').isHidden(), 'Triage is first and emergency help needs no login');
  await page.screenshot({ path: path.join(output,'emergency-desktop.png') });
  await click('#emergencyUnknownBtn');
  check((await text('#emergencyUnconsciousResult')).includes('Позвоните 112'), 'Unknown glucose prioritizes ambulance and breathing');
  await click('[data-aid-breathing="abnormal"]');
  check((await text('#aidBreathingResult')).includes('СЛР') && !await page.locator('[data-aid-guide="glucagon"]').count(), 'Abnormal breathing shows CPR without injection distraction');
  await click('[data-aid-breathing="normal"]');
  await click('#aidGlucagonDetails > summary');
  const glucagon = page.locator('[data-aid-guide="glucagon"]');
  check(await glucagon.isVisible(), 'Glucagon guide available after normal breathing');
  for (let i=1;i<5;i++) await glucagon.locator('[data-aid-guide-action="next"]').click();
  check((await glucagon.innerText()).includes('Введите и оставайтесь рядом'), 'All glucagon steps navigable');
  await chooseState('#emergencyConsciousBtn');
  check(await page.locator('.aid-triage').isHidden() && await page.locator('#aidChangeState').isVisible(), 'Current stage has focus and reassessment remains available');
  const guide = page.locator('[data-aid-guide="measure"]');
  await guide.locator('[data-aid-guide-action="next"]').click();
  check((await guide.innerText()).includes('Вставьте тест-полоску'), 'Measurement guide advances one action at a time');
  await guide.locator('[data-aid-guide-action="motion"]').click();
  check(await guide.evaluate(e=>e.classList.contains('is-paused')), 'Animation can be paused independently');
  await guide.locator('[data-aid-guide-target="3"]').click();
  check(await guide.getAttribute('data-aid-guide-step') === '3' && await guide.locator('[data-aid-scene="sample"]').count() === 1, 'Numbered navigation opens the requested scene');
  await guide.locator('[data-aid-guide-action="motion"]').click();
  await guide.locator('[data-aid-guide-action="replay"]').click();
  check(await guide.getAttribute('data-aid-guide-step') === '3', 'Replaying an animation never advances a medical instruction');
  const timing = await guide.locator('.aid-sample-touch').evaluate(e => {
    const style = getComputedStyle(e);
    return {count:style.animationIterationCount, fill:style.animationFillMode};
  });
  check(timing.count === '1' && timing.fill === 'both', 'Demonstration plays once and preserves its final frame');
  await guide.locator('[data-aid-guide-target="5"]').click();
  await guide.locator('[data-aid-guide-action="reading"]').click();
  check(await page.locator('#emergencySugarValue').evaluate(e=>e===document.activeElement), 'Completing measurement focuses the actual reading field');
  await page.screenshot({ path: path.join(output,'emergency-measurement.png') });
  for (const [value,unit,expected] of [['3,9','mmol','Низкий сахар'],['2.9','mmol','Очень низкий сахар'],['4','mmol','Сахар не снижен'],['10','mmol','Сахар не снижен'],['10.1','mmol','Высокий сахар'],['71','mgdl','Низкий сахар'],['72','mgdl','Сахар не снижен'],['53','mgdl','Очень низкий сахар'],['181','mgdl','Высокий сахар']]) {
    await reading(value,unit); check((await text('.aid-result-header h3'))===expected, `${value} ${unit} automatically classified`);
  }
  await reading('abc');
  check(await page.locator('#aidReadingError').isVisible() && await page.locator('#emergencyResult').isHidden(), 'Invalid input clears stale advice and shows inline error');
  await chooseState('#emergencyConsciousBtn');
  check(await page.locator('#aidReadingError').isHidden() && await page.locator('#emergencySugarValue').inputValue() === '' && await page.locator('#emergencySugarValue').getAttribute('aria-invalid') === null, 'Fresh state assessment clears the old reading and its validation error');
  await reading('HI');
  check((await text('#emergencyResult')).includes('выше диапазона') && !await page.locator('#emergencyCorrectionCalculate').count(), 'HI cannot produce numeric dose');
  await reading('LO');
  check((await text('#emergencyResult')).includes('Очень низкий'), 'LO enters immediate hypo flow');
  check(await page.locator('#aidMeasurement').isHidden() && await page.locator('#aidNewReading').isVisible(), 'Reading result replaces the previous measuring stage');
  check(await page.locator('.aid-sequence > li:visible').count() === 1 && await page.locator('.aid-deterioration').isVisible(), 'One action is shown with critical deterioration advice kept visible');
  await click('[data-aid-sequence-step="1"]');
  check(await page.locator('#aidStartTimer').isVisible() && await page.locator('.aid-sequence > li:visible').count() === 1, 'Manual action navigation reveals the retest timer');
  await click('#aidStartTimer');
  check((await text('#aidTimerValue')) === '15:00', 'Timer starts only after carbohydrate action');
  await close(); await click('#publicEmergencyBtn'); await click('#aidTimerMeasure');
  check(await page.locator('#aidStateTitle').evaluate(e=>e===document.activeElement), 'Retest after reopening returns to conscious-state assessment');
  await chooseState('#emergencyConsciousBtn');
  await page.clock.fastForward(15*60*1000);
  check((await text('#aidTimerValue')) === '00:00' && (await text('#aidTimerAnnouncement')).includes('Пора'), 'Timer remains correct after time jump and announces retest');
  await reading('3'); await click('#emergencyUnconsciousLowBtn'); await click('[data-aid-breathing="normal"]');
  check((await text('#emergencyUnconsciousResult')).includes('При тяжёлой гипогликемии') && !await page.locator('#aidMeasurement').isVisible(), 'Loss of consciousness replaces oral sugar advice with low-glucose emergency flow');
  await click('#aidCriticalReadingDetails > summary'); await fill('aidCriticalValue','18'); await click('#aidCriticalReadingForm button');
  check((await text('#emergencyUnconsciousResult')).includes('Высокий сахар') && !await page.locator('[data-aid-guide="glucagon"]').count(), 'Known high sugar while unconscious shows separate algorithm without glucagon');
  await close();
  await click('#switchToRegister'); await fill('regUsername','Первая помощь'); await fill('regPassword','emergency-test-2026'); await fill('regPasswordConfirm','emergency-test-2026'); await click('#registerBtn'); await click('#setupSkip');
  await click('#profileBtn'); await fill('profileShortInsulinName','Тестовый назначенный препарат'); await click('[data-settings="calc"]');
  for (const [id,value] of [['profileCorrectionTarget',6],['profileCorrectionFactor',2],['profileCorrectionStep',0.5],['profileCorrectionMax',6]]) await fill(id,value);
  await page.locator('#profileCorrectionConfirmed').check(); await click('#saveProfileBtn');
  check(await page.locator('#profileModal').isHidden(), 'Personal correction plan validates and saves');
  await click('#profileBtn');
  check(await page.locator('#profileCorrectionConfirmed').isChecked() && await page.locator('#profileCorrectionFactor').inputValue()==='2', 'Saved correction plan roundtrips into settings');
  await fill('profileShortInsulinName','Другой препарат');
  check(!await page.locator('#profileCorrectionConfirmed').isChecked(), 'Changing insulin revokes plan confirmation');
  await fill('profileShortInsulinName','Тестовый назначенный препарат'); await click('[data-settings="calc"]');
  await page.locator('#profileCorrectionConfirmed').check(); await fill('profileCorrectionFactor','2.5');
  check(!await page.locator('#profileCorrectionConfirmed').isChecked(), 'Changing sensitivity revokes plan confirmation');
  await close();
  await click('#emergencyBtn'); await chooseState('#emergencyConsciousBtn'); await reading('14');
  await click('#emergencyCorrectionCalculate');
  check(!(await text('#emergencyCorrectionResult')).includes('ЕД'), 'Unchecked gates do not reveal dose');
  for(const id of ['correctionAdult','correctionOwnPlan','correctionNoRedFlags','correctionNoKetones','correctionSourceConfirmed','correctionRecentPlan']) await page.locator('#'+id).check();
  await page.locator('#correctionActiveSource').selectOption('pump'); await fill('correctionActiveInsulin','1');
  await fill('correctionLastDose',await page.evaluate(()=>{const d=new Date(Date.now()-6*3600000); const pad=n=>String(n).padStart(2,'0');return `${d.getFullYear()}-${pad(d.getMonth()+1)}-${pad(d.getDate())}T${pad(d.getHours())}:${pad(d.getMinutes())}`;}));
  await click('#emergencyCorrectionCalculate');
  check((await text('#emergencyCorrectionResult .result-value'))==='3 ЕД', 'Personal formula uses active insulin and produces expected dose');
  await page.locator('#correctionNoKetones').uncheck();
  check(await page.locator('#emergencyCorrectionResult').isHidden(), 'Changing safety gate revokes numeric result immediately');
  await page.clock.fastForward(5*60*1000);
  await fill('correctionActiveInsulin','0.5'); await click('#emergencyCorrectionCalculate');
  check((await text('#emergencyCorrectionResult')).includes('устарели') && !await page.locator('#emergencyCorrectionResult .result-value').count(), 'Expired calculator remains explainable and never shows a dose after editing');
  await click('[data-aid-redflags]');
  await reading('14');
  check(!await page.locator('#emergencyCorrectionCalculate').count(), 'Reported red flags stay latched across repeated results');
  await close(); await click('#emergencyBtn'); await chooseState('#emergencyConsciousBtn'); await reading('14');
  await click('#emergencyUnconsciousHighBtn');
  check(!await page.locator('#emergencyCorrectionCalculate').count(), 'Critical state revokes all correction controls');
  await close(); await click('#logoutBtn');
  check((await page.locator('#aidThresholdNote').textContent())==='', 'Lock also scrubs private targets from hidden DOM');
  await click('#publicEmergencyBtn');
  check(!(await text('#emergencyModal')).includes('Тестовый назначенный препарат'), 'Locked emergency help reveals no profile medication');
  await page.setViewportSize({width:390,height:844});
  await chooseState('#emergencyConsciousBtn'); await reading('2,8');
  await page.screenshot({path:path.join(output,'emergency-mobile.png')});
  for(const width of [320,390,768]){
    await page.setViewportSize({width,height:844});
    check(await page.locator('.aid-shell').evaluate(e=>e.scrollWidth<=e.clientWidth+1), `No horizontal overflow at ${width}px`);
  }
  await page.emulateMedia({reducedMotion:'reduce'}); await close(); await click('#publicEmergencyBtn'); await chooseState('#emergencyConsciousBtn');
  check(await page.locator('[data-aid-guide="measure"]').evaluate(e=>e.classList.contains('is-paused')), 'System reduced motion initializes guide paused');
  await guide.locator('[data-aid-guide-target="1"]').click();
  check(await guide.locator('.aid-insert-strip').evaluate(e=>getComputedStyle(e).animationName==='none' && new DOMMatrix(getComputedStyle(e).transform).m42===0), 'Reduced motion shows the strip already seated in the meter');
  check(await guide.locator('[data-aid-guide-action="motion"]').isDisabled() && await guide.locator('[data-aid-guide-action="replay"]').isDisabled(), 'Static mode does not promise unavailable playback');
  await page.evaluate(()=>{document.documentElement.dataset.theme='dark';document.documentElement.classList.add('high-contrast','large-text');});
  await page.setViewportSize({width:320,height:844});
  check(await guide.evaluate(e=>e.scrollWidth<=e.clientWidth+1) && await page.locator('.aid-shell').evaluate(e=>e.scrollWidth<=e.clientWidth+1), 'Illustrated guide fits 320px with large text and high contrast');
  check(await guide.locator('.aid-guide-copy > p').evaluate(e=>parseFloat(getComputedStyle(e).fontSize)>=20), 'Large-text preference increases instruction text');
  await page.screenshot({path:path.join(output,'emergency-guide-accessible.png')});
  await reading('15');
  check(await page.locator('.aid-shell').evaluate(e=>e.scrollWidth<=e.clientWidth+1), 'Dark theme and large text do not overflow');
  await page.screenshot({path:path.join(output,'emergency-dark.png')});
  const duplicateIds=await page.evaluate(()=>{const seen=new Set();return [...document.querySelectorAll('[id]')].filter(e=>{if(seen.has(e.id))return true;seen.add(e.id);return false;}).map(e=>e.id)});
  check(!duplicateIds.length,'No duplicate element IDs');
  check(!errors.length, `No browser errors: ${errors.join('; ')}`);
  check(!requests.length,'All guides and first-aid flows work offline');
  console.log(`${checks} emergency checks passed. Screenshots: ${output}`);
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();});
